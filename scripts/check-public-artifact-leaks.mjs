#!/usr/bin/env node
/**
 * check-public-artifact-leaks — scan a directory that is about to be pushed to
 * a PUBLIC repository and fail if it carries anything that belongs only to the
 * private source it was generated from.
 *
 * The emitters already scrub on the way out. This is the check on the result:
 * it reads the finished tree, so a scrubber that stops matching, a new file
 * outside the scrubbed set, or a hand edit in the public repo all surface here
 * instead of on the public internet.
 *
 * It also ships inside the public plugin repos (their own CI runs it on every
 * pull request), so its source must pass its own scan: no literal example of
 * anything it forbids appears below. Names are matched by SHA-256 of the
 * lowercased token, which keeps them out of a public file. That is
 * obscurity, not secrecy, and only meant to be.
 *
 *   node scripts/check-public-artifact-leaks.mjs <dir> [--no-gitleaks] [--gitleaks-config <file>]
 *
 * Exits 1 on any finding (from either scan), 2 on a usage or setup error.
 */
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, extname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Kept equal to ANNOTATION_PREFIXES in the bundler's annotation stripper; the
// monorepo test fails when the two lists differ. Copied, not imported, because
// this file also runs where the stripper does not exist.
export const ANNOTATION_PREFIXES = [
  'skill-options:',
  'skill-flow:',
  'lite:keep-',
  'lite:skip-',
  'voice:allow',
  'fragment:',
  'pilot:',
];

// Hosts under the product domain that users are meant to see. Every other
// subdomain (environments, tenants, consoles) is internal by default, so a new
// host has to be added here deliberately rather than slipping through.
export const PUBLIC_HOSTS = new Set([
  'app.ritualapp.cloud',
  'api.ritualapp.cloud',
  'auth.ritualapp.cloud',
  'mcp.ritualapp.cloud',
  'chatgpt.ritualapp.cloud',
]);

// sha256(lowercased token or two-token phrase), first 16 hex characters.
const HASHED_TERMS = new Map([
  ['64b4d0f47c93ce23', 'team-name'],
  ['32aa7080f93fe27d', 'team-name'],
  ['c157a0b0d40f9d95', 'team-name'],
  ['e012e7105e6ea530', 'team-name'],
  ['0c361db89c43ec67', 'team-name'],
  ['7da604dc02a7d907', 'team-name'],
  ['6487f6c4ee2f88de', 'team-name'],
  ['bde739c27eadbf06', 'team-name'],
  ['9275cbba81c2f4c9', 'private-repo'],
]);

export const RULES = [
  {
    id: 'pr-ref',
    // Three to five digits: the private repo's pull requests. An owner/repo
    // prefix (a public upstream issue) and HTML entities are not references.
    re: /(?<![\w&/#.-])#\d{3,5}\b/g,
    skipExt: new Set(['.svg', '.css']),
    why: 'a pull request number from the private repo means nothing to a public reader',
  },
  {
    id: 'internal-path',
    re: /\bapps\/[\w.-]+\/src\b|\bdocuments\/(?:architecture|reviews|design|postmortems)\b|~\/\.claude\/plans\b|\.claude\/worktrees\b/g,
    why: 'a path into the private source tree or a developer machine is a dead pointer in public',
  },
  {
    id: 'annotation',
    re: new RegExp(
      `<!--\\s*(?:${ANNOTATION_PREFIXES.map((p) => p.replace(/[.*+?^${}()|[\]\\-]/g, '\\$&')).join('|')})`,
      'g',
    ),
    why: 'an authoring annotation the bundler should have stripped',
  },
  {
    id: 'dated-note',
    re: /<!--(?:(?!-->)[\s\S])*?\b20\d{2}-\d{2}-\d{2}\b(?:(?!-->)[\s\S])*-->/g,
    why: 'a dated HTML comment is a review or changelog note, not product text',
  },
  {
    id: 'internal-email',
    re: /[\w.%+-]+@ritual\.work\b/g,
    why: 'a staff address does not belong in a public artifact',
  },
  {
    id: 'internal-host',
    re: /\b(?:[a-z0-9-]+\.)+ritualapp\.cloud\b|\b[\w.-]+\.(?:svc\.cluster\.local|rds\.amazonaws\.com|eks\.amazonaws\.com)\b/gi,
    keep: (m) => !PUBLIC_HOSTS.has(m.toLowerCase()),
    why: 'only the public product hosts may ship; environment and tenant hosts are internal',
  },
];

const HASH_WHY = {
  'team-name': "a team member's name does not belong in a public artifact",
  'private-repo': 'names the private GitHub organisation or one of its repositories',
};

/*
 * Legitimate matches, each with the reason it may ship. An entry applies to
 * the rules it names and matches the found text; a finding is dropped only
 * when one entry covers it.
 */
export const ALLOWLIST = [
  {
    rules: ['dated-note'],
    match: /^<!--\s*Generated by Ritual\b/,
    reason:
      'output template the skill writes into users’ PR descriptions and briefs; its date is a placeholder filled at run time',
  },
  {
    rules: ['dated-note'],
    match: /^<!--\s*Refreshed at\b/,
    reason: 'output template the skill writes into users’ files to record a refresh time',
  },
  {
    rules: ['dated-note'],
    match: /^<!--\s*source-sha:/,
    reason: 'provenance stamp written by the generator so a reader can tell which build a file came from',
  },
  {
    rules: ['pr-ref'],
    match: /^#75961$/,
    reason:
      'a public Claude Code issue the claude-plugin sync script cites (with its owner/repo on first mention), not a private pull request',
  },
];

/*
 * Legitimate patterns no rule matches, listed so nobody widens a rule into
 * them. The test pins each one as clean.
 */
export const NOT_FLAGGED = [
  {
    sample: '~/.claude/skills/ritual/SKILL.md',
    reason:
      'the user’s own agent config directory; only the plans and worktrees subdirectories are developer-machine paths',
  },
  {
    sample: 'git clone the source repo next to this one: ../ritual-enterprise',
    reason:
      'contributing guides name the sibling checkout the sync reads from; the repository name alone is not private',
  },
];

const SKIP_DIRS = new Set(['.git', 'node_modules']);
const MAX_BYTES = 5 * 1024 * 1024;

const shortHash = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);

function allowed(rule, text) {
  return ALLOWLIST.some((a) => a.rules.includes(rule) && a.match.test(text));
}

function position(text, index) {
  const before = text.slice(0, index);
  const line = before.split('\n').length;
  return { line, col: index - before.lastIndexOf('\n') };
}

function snippet(text) {
  const flat = text.replace(/\s+/g, ' ').trim();
  return flat.length > 80 ? `${flat.slice(0, 77)}...` : flat;
}

/** Findings for one file's text. `file` is only used for reporting and extension checks. */
export function scanText(text, file = '') {
  const findings = [];
  const ext = extname(file).toLowerCase();
  for (const rule of RULES) {
    if (rule.skipExt?.has(ext)) continue;
    for (const m of text.matchAll(rule.re)) {
      if (rule.keep && !rule.keep(m[0])) continue;
      if (allowed(rule.id, m[0])) continue;
      findings.push({ file, rule: rule.id, ...position(text, m.index), text: snippet(m[0]), why: rule.why });
    }
  }
  const tokens = [...text.matchAll(/[A-Za-z0-9][A-Za-z0-9-]*/g)];
  tokens.forEach((t, i) => {
    const candidates = [t[0]];
    const next = tokens[i + 1];
    if (next && text.slice(t.index + t[0].length, next.index) === ' ') candidates.push(`${t[0]} ${next[0]}`);
    for (const c of candidates) {
      const rule = HASHED_TERMS.get(shortHash(c.toLowerCase()));
      if (!rule || allowed(rule, c)) continue;
      findings.push({ file, rule, ...position(text, t.index), text: snippet(c), why: HASH_WHY[rule] });
    }
  });
  return findings;
}

function* walk(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const path = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(path);
    else if (entry.isFile()) yield path;
  }
}

/** Findings for every text file under `root`. Binary and oversized files are skipped. */
export function scanDir(root) {
  const findings = [];
  let files = 0;
  for (const path of walk(root)) {
    if (statSync(path).size > MAX_BYTES) continue;
    const buf = readFileSync(path);
    if (buf.subarray(0, 8000).includes(0)) continue;
    files++;
    findings.push(...scanText(buf.toString('utf8'), relative(root, path)));
  }
  return { files, findings };
}

function runGitleaks(root, config) {
  const args = ['detect', '--no-git', '--source', root, '--no-banner', '--redact', '--exit-code', '1'];
  if (config) args.push('--config', config);
  const res = spawnSync('gitleaks', args, { stdio: 'inherit' });
  if (res.error?.code === 'ENOENT') {
    console.error('✗ gitleaks is not installed; install it, or pass --no-gitleaks to run only the pattern scan.');
    process.exit(2);
  }
  return res.status === 0;
}

function main(argv) {
  const args = argv.slice(2);
  const take = (flag) => {
    const i = args.indexOf(flag);
    return i === -1 ? undefined : args.splice(i, 2)[1];
  };
  const noGitleaks = args.includes('--no-gitleaks');
  const configArg = take('--gitleaks-config');
  const dirArg = args.find((a) => !a.startsWith('--'));
  if (!dirArg || !existsSync(dirArg) || !statSync(dirArg).isDirectory()) {
    console.error('usage: check-public-artifact-leaks.mjs <dir> [--no-gitleaks] [--gitleaks-config <file>]');
    process.exit(2);
  }
  const root = resolve(dirArg);

  const { files, findings } = scanDir(root);
  for (const f of findings) console.error(`${f.file}:${f.line}:${f.col}  ${f.rule}  "${f.text}"  — ${f.why}`);

  let gitleaksOk = true;
  if (!noGitleaks) {
    // The source repo's config when this runs from there; gitleaks' defaults elsewhere.
    const local = join(dirname(fileURLToPath(import.meta.url)), '..', '.gitleaks.toml');
    gitleaksOk = runGitleaks(root, configArg ?? (existsSync(local) ? local : undefined));
  }

  if (findings.length || !gitleaksOk) {
    const parts = [];
    if (findings.length) parts.push(`${findings.length} pattern finding(s)`);
    if (!gitleaksOk) parts.push('gitleaks findings');
    console.error(`✗ ${dirArg}: ${parts.join(' and ')} in ${files} file(s). Nothing here may be published.`);
    process.exit(1);
  }
  console.log(`✓ ${dirArg}: ${files} file(s) clean${noGitleaks ? ' (pattern scan only)' : ', gitleaks clean'}.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv);
